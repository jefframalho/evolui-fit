import ts from 'typescript';
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {z} from 'zod';
const context={z};vm.createContext(context);
vm.runInContext(ts.transpile(fs.readFileSync('lib/record-validation.ts','utf8').replace("import {z} from 'zod';",'').replace('export const RecordDraftSchema=','globalThis.schema='),{target:ts.ScriptTarget.ES2022}),context);
const parse=(kind,data,date='2026-11-07')=>context.schema.safeParse({kind,date,data});
assert.equal(parse('measure',{weight:'100'}).data.data.weight,100);
assert.equal(parse('measure',{weight:-1}).success,false);
assert.equal(parse('measure',{}).success,false);
assert.equal(parse('habit',{water:'1.5',sleep:'8'}).success,true);
assert.equal(parse('habit',{sleep:25}).success,false);
assert.equal(parse('goal',{weekly:3.5}).success,false);
assert.equal(parse('goal',{targetWeight:'90',weekly:'4'}).success,true);
assert.equal(parse('workout',{name:'QA',duration:'30',exercises:[{name:'Supino',sets:'3',reps:'10',load:'0'}]}).success,true);
assert.equal(parse('workout',{name:'QA',duration:30,exercises:[]}).success,false);
assert.equal(parse('measure',{weight:100},'2026-02-31').success,false);
console.log('PASS: validação de treinos, medidas, hábitos, metas, datas e conversão numérica.');

assert.equal(parse('schedule',{title:'Pernas',time:'18:30',duration:'60',type:'Treino',status:'planned'}).success,true);
assert.equal(parse('schedule',{title:'Pernas',time:'25:30',duration:60,type:'Treino',status:'planned'}).success,false);
assert.equal(parse('schedule',{title:'',time:'18:30',duration:60,type:'Treino',status:'planned'}).success,false);
assert.equal(parse('schedule',{title:'Descanso',time:'18:30',duration:0,type:'Descanso',status:'planned'}).success,false);
console.log('PASS: validação da agenda semanal e horários.');
